export const minPrice = (p: Product) => Math.min(...p.sizes.map((s) => s.price));

export const relatedProducts = (p: Product, count = 4) =>
  products
    .filter((x) => x.id !== p.id)
    .map((x) => ({
      x,
      score:
        x.families.filter((f) => p.families.includes(f)).length * 3 +
        (x.gender === p.gender ? 1 : 0) +
        (x.intensity === p.intensity ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score || b.x.rating - a.x.rating)
    .slice(0, count)
    .map((r) => r.x);

export const priceBounds = {
  min: Math.min(...products.flatMap((p) => p.sizes.map((s) => s.price))),
  max: Math.max(...products.flatMap((p) => p.sizes.map((s) => s.price))),
};
